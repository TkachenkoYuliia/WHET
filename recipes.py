def normalize_ingredient(name: str) -> str | None:
    """Нормалізує назву інгредієнта за допомогою аліасів."""
    name_lower = name.lower().strip()
    for standard, aliases in INGREDIENT_ALIASES.items():
        if name_lower in aliases or any(a in name_lower for a in aliases):
            return standard
    return name_lower if name_lower else None


# Продукти, які зазвичай є в кожній кухні (не потрібно вказувати)
PANTRY = {"сіль", "перець", "олія", "масло", "цукор"}


def get_recipes_by_ingredients(user_products: dict) -> list:
    """
    user_products: {назва: (кількість, одиниця)}
    Повертає список рецептів, для яких достатньо інгредієнтів.
    """
    available = {}
    for name, (qty, unit) in user_products.items():
        norm = normalize_ingredient(name) or name.lower().strip()
        if norm:
            if norm in available:
                old_q, old_u = available[norm]
                available[norm] = (old_q + qty, old_u)
            else:
                available[norm] = (qty, unit)

    result = []
    for r in RECIPES:
        missing_main = 0
        for ing, (min_qty, min_unit) in r["ingredients"].items():
            norm_ing = normalize_ingredient(ing) or ing.lower()
            if norm_ing in PANTRY:
                continue
            if norm_ing not in available:
                missing_main += 1
                continue
            avail_qty, avail_unit = available[norm_ing]
            if min_unit == "шт" and avail_unit in ("шт", "штук", "штуки", "г"):
                if avail_qty < min_qty * 0.8:
                    missing_main += 1
            else:
                if avail_qty < min_qty * 0.6:
                    missing_main += 1
        if missing_main == 0:
            result.append(r)
    return result


def generate_menu_variants(recipes: list, count: int = 3) -> list[list[dict]]:
    """
    Генерує count варіантів збалансованого меню на день.
    Кожне меню: сніданок, обід, вечеря. Без повторень страв в одному варіанті.
    """
    import random

    breakfasts = [r for r in recipes if r["meal_type"] == "breakfast"]
    lunches = [r for r in recipes if r["meal_type"] == "lunch"]
    dinners = [r for r in recipes if r["meal_type"] == "dinner"]

    # Збираємо всі унікальні рецепти для fallback (коли немає страв певного типу)
    all_by_type = {"breakfast": breakfasts, "lunch": lunches, "dinner": dinners}
    fallback_pool = [r for r in recipes if r not in (breakfasts + lunches + dinners)] or recipes

    def get_for_meal(meal_type: str, exclude_ids: set) -> dict | None:
        """Повертає рецепт для типу прийому їжі, виключаючи вже обрані."""
        pool = all_by_type.get(meal_type) or fallback_pool
        available = [r for r in pool if r["id"] not in exclude_ids]
        if not available:
            available = [r for r in recipes if r["id"] not in exclude_ids]
        return random.choice(available) if available else None

    variants = []
    used_combos = set()

    for _ in range(count * 3):
        if len(variants) >= count:
            break

        used = set()
        b = get_for_meal("breakfast", used)
        if b:
            used.add(b["id"])
        l = get_for_meal("lunch", used)
        if l:
            used.add(l["id"])
        d = get_for_meal("dinner", used)
        if d:
            used.add(d["id"])

        if not all((b, l, d)):
            continue

        combo = (b["id"], l["id"], d["id"])
        if combo not in used_combos:
            used_combos.add(combo)
            variants.append([b, l, d])

    return variants[:count]
